def _deleted(el):
    return any(a.tag == qn("w:del") for a in el.iterancestors())


def _text_runs(p):
    return [r for r in p.iter(qn("w:r")) if not _deleted(r) and r.find(qn("w:t")) is not None]


def ptext(p):
    return "".join("".join(t.text or "" for t in r.findall(qn("w:t"))) for r in _text_runs(p))


def _split(r, off):
    """런 r을 off 글자에서 둘로 나누고 뒤쪽 런을 돌려준다(단일 w:t 런 가정)."""
    t = r.find(qn("w:t"))
    s = t.text or ""
    if off <= 0 or off >= len(s):
        return None
    r2 = copy.deepcopy(r)
    t.set(XML_SPACE, "preserve")
    t.text = s[:off]
    t2 = r2.find(qn("w:t"))
    t2.text = s[off:]
    t2.set(XML_SPACE, "preserve")
    r.addnext(r2)
    return r2


def _normalize(p):
    """한 런에 w:t가 여러 개면 런을 나눠 '런 1개 = w:t 1개'로 만든다."""
    for r in _text_runs(p):
        ts = r.findall(qn("w:t"))
        if len(ts) > 1:
            prev = r
            for t in ts[1:]:
                nr = copy.deepcopy(r)
                for c in list(nr):
                    if c.tag != qn("w:rPr"):
                        nr.remove(c)
                r.remove(t)
                nr.append(t)
                prev.addnext(nr)
                prev = nr


def _ins_run(text, rpr):
    ins = OxmlElement("w:ins")
    ins.set(qn("w:id"), _id())
    ins.set(qn("w:author"), AUTHOR)
    ins.set(qn("w:date"), DATE)
    r = OxmlElement("w:r")
    if rpr is not None:
        r.append(copy.deepcopy(rpr))
    t = OxmlElement("w:t")
    t.set(XML_SPACE, "preserve")
    t.text = text
    r.append(t)
    ins.append(r)
    return ins, r


def _comment(p, r, text):
    if text:
        doc.add_comment(Run(r, Paragraph(p, doc._body)), text=text, author=AUTHOR, initials=INITIALS)


def track_replace(p, old, new, comment=None, nth=0):
    """문단 p의 old(nth번째)를 삭제 표시하고 new를 삽입 표시한다. new가 ''이면 삭제만."""
    _normalize(p)
    full = ptext(p)
    pos = -1
    for _ in range(nth + 1):
        pos = full.find(old, pos + 1)
    assert pos >= 0, (old, full[:120])
    s, e = pos, pos + len(old)
    # 경계에서 런 분할
    for bound in (s, e):
        acc = 0
        for r in _text_runs(p):
            n = len(r.find(qn("w:t")).text or "")
            if acc < bound < acc + n:
                _split(r, bound - acc)
                break
            acc += n
    acc, hit = 0, []
    for r in _text_runs(p):
        n = len(r.find(qn("w:t")).text or "")
        if acc >= s and acc + n <= e and n:
            hit.append(r)
        acc += n
    rpr = hit[0].find(qn("w:rPr"))
    d = OxmlElement("w:del")
    d.set(qn("w:id"), _id())
    d.set(qn("w:author"), AUTHOR)
    d.set(qn("w:date"), DATE)
    hit[0].addprevious(d)
    for r in hit:
        t = r.find(qn("w:t"))
        t.tag = qn("w:delText")
        d.append(r)
    anchor = hit[-1]
    if new:
        ins, anchor = _ins_run(new, rpr)
        d.addnext(ins)
    _comment(p, anchor, comment)


def track_insert(p, new, after=None, comment=None):
    """문단 p에서 after 문자열 바로 뒤(없으면 문단 끝)에 new를 삽입 표시한다."""
    _normalize(p)
    runs = _text_runs(p)
    if after is None:
        last = runs[-1] if runs else None
        rpr = last.find(qn("w:rPr")) if last is not None else None
        ins, r = _ins_run(new, rpr)
        if last is not None:
            last.addnext(ins)
        else:
            p.append(ins)
    else:
        full = ptext(p)
        pos = full.find(after)
        assert pos >= 0, (after, full[:120])
        e = pos + len(after)
        acc = 0
        for rr in _text_runs(p):
            n = len(rr.find(qn("w:t")).text or "")
            if acc < e < acc + n:
                _split(rr, e - acc)
                break
            acc += n
        acc, prev = 0, None
        for rr in _text_runs(p):
            acc += len(rr.find(qn("w:t")).text or "")
            if acc == e:
                prev = rr
                break
        ins, r = _ins_run(new, prev.find(qn("w:rPr")))
        prev.addnext(ins)
    _comment(p, r, comment)


